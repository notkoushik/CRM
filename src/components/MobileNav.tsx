export function MobileNav({ page, onNavigate, userRole }: MobileNavProps) {
  const items = navItemsForRole(userRole);

  return (
    <nav
      className="fixed inset-x-0 bottom-0 z-40 overflow-x-auto border-t border-[var(--color-line)] bg-[var(--color-panel)] lg:hidden"
      style={{ paddingBottom: 'max(0.5rem, env(safe-area-inset-bottom))' }}
      aria-label="Mobile Navigation"
    >
      <div className="mx-auto flex min-w-max justify-around">
        {items.map((item) => {
          const active = page === item.id;
          return (
            <button
              key={item.id}
              type="button"
              aria-current={active ? 'page' : undefined}
              onClick={() => onNavigate(item.id)}
              className={`flex min-h-14 min-w-[3.75rem] flex-1 flex-col items-center justify-center gap-1 px-2 py-2 text-[10px] font-semibold transition ${
                active ? 'text-teal-700' : 'text-stone-500 hover:text-stone-800'
              }`}
            >
              <span
                className={`flex h-8 w-8 items-center justify-center rounded-md transition ${
                  active ? 'bg-teal-50 text-teal-700' : 'text-stone-500'
                }`}
              >
                <NavIcon page={item.id} />
              </span>
              <span>{item.short}</span>
            </button>
          );
        })}
      </div>
    </nav>
  );
}
